"""
AURA Backend — Detection & AI Event Models
=============================================
Stores AI/CV object detections and AI-generated events.
"""

import uuid
from datetime import datetime, timezone
from sqlalchemy import (
    Column, String, Float, DateTime, Text, ForeignKey, Index
)
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import relationship
from app.database import Base


class Detection(Base):
    """Object detection from computer vision (YOLO)."""
    __tablename__ = "detections"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    robot_id = Column(
        UUID(as_uuid=True),
        ForeignKey("robots.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    object_type = Column(String(50), nullable=False)  # "person", "vehicle", "animal", "bag", "obstacle"
    confidence = Column(Float, nullable=False)
    bounding_box = Column(JSONB, nullable=True)  # {"x": 0, "y": 0, "w": 100, "h": 100}
    image_path = Column(String(500), nullable=True)
    timestamp = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )

    # Relationships
    robot = relationship("Robot", back_populates="detections")

    __table_args__ = (
        Index("ix_detections_robot_timestamp", "robot_id", "timestamp"),
        Index("ix_detections_object_type", "object_type"),
    )

    def __repr__(self):
        return f"<Detection {self.object_type} ({self.confidence:.2f}) robot={self.robot_id}>"


class AIEvent(Base):
    """Events generated by AI services (anomaly detection, NLP commands, etc.)."""
    __tablename__ = "ai_events"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    robot_id = Column(
        UUID(as_uuid=True),
        ForeignKey("robots.id", ondelete="CASCADE"),
        nullable=True,
    )
    event_type = Column(String(50), nullable=False)  # "detection", "anomaly", "nl_command"
    source = Column(String(50), nullable=False)  # "yolo", "anomaly_detector", "nl_interpreter"
    description = Column(Text, nullable=True)
    data = Column(JSONB, nullable=True)
    timestamp = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    __table_args__ = (
        Index("ix_ai_events_type_timestamp", "event_type", "timestamp"),
    )

    def __repr__(self):
        return f"<AIEvent {self.event_type} from {self.source}>"
