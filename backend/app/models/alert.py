"""
AURA Backend — Alert Model
============================
Alerts generated by anomaly detection, sensor thresholds, or system events.
"""

import uuid
import enum
from datetime import datetime, timezone
from sqlalchemy import (
    Column, String, DateTime, Enum, Text, ForeignKey, Index
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
from app.database import Base


class AlertType(str, enum.Enum):
    """Type of alert condition."""
    HIGH_GAS = "HIGH_GAS"
    LOW_BATTERY = "LOW_BATTERY"
    HIGH_TEMPERATURE = "HIGH_TEMPERATURE"
    OBSTACLE_DETECTED = "OBSTACLE_DETECTED"
    COMMUNICATION_LOST = "COMMUNICATION_LOST"
    SENSOR_FAILURE = "SENSOR_FAILURE"
    INTRUSION_DETECTED = "INTRUSION_DETECTED"
    SYSTEM_ERROR = "SYSTEM_ERROR"
    MOTOR_FAILURE = "MOTOR_FAILURE"
    EMERGENCY_STOP = "EMERGENCY_STOP"


class AlertSeverity(str, enum.Enum):
    """Alert severity level."""
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


class AlertStatus(str, enum.Enum):
    """Alert lifecycle status."""
    ACTIVE = "ACTIVE"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"


class Alert(Base):
    __tablename__ = "alerts"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    robot_id = Column(
        UUID(as_uuid=True),
        ForeignKey("robots.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    type = Column(Enum(AlertType), nullable=False)
    severity = Column(Enum(AlertSeverity), nullable=False)
    title = Column(String(200), nullable=False)
    message = Column(Text, nullable=False)
    status = Column(
        Enum(AlertStatus), nullable=False, default=AlertStatus.ACTIVE
    )
    source = Column(String(100), nullable=True)  # e.g., "anomaly_detection", "sensor"
    created_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )
    acknowledged_at = Column(DateTime(timezone=True), nullable=True)
    acknowledged_by = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    resolved_at = Column(DateTime(timezone=True), nullable=True)

    # Relationships
    robot = relationship("Robot", back_populates="alerts")
    acknowledged_by_user = relationship(
        "User", back_populates="acknowledged_alerts", foreign_keys=[acknowledged_by]
    )

    __table_args__ = (
        Index("ix_alerts_robot_created", "robot_id", "created_at"),
        Index("ix_alerts_status_severity", "status", "severity"),
    )

    def __repr__(self):
        return f"<Alert {self.type.value} [{self.severity.value}] - {self.status.value}>"
